"""Fast CPU unit tests (no GPU, no model):  python src/test_units.py
Covers: metric formulas (hand-computed values), empty-evidence rules, output parser, and patient-split integrity."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from metrics import INVALID, classification_report, evidence_report, evidence_row_scores  # noqa: E402
from prompts import INCLUSION_LABELS, parse_output, split_sentences  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
n_ok = 0


def check(name, cond):
    global n_ok
    print(("PASS " if cond else "FAIL ") + name)
    assert cond, name
    n_ok += 1


def close(a, b, eps=1e-9):
    return abs(a - b) < eps


# ---- classification metrics (hand-computed)
gold = ["included", "not included", "not enough information", "included"]
pred = ["included", "included", None, "not enough information"]
r = classification_report(gold, pred, INCLUSION_LABELS)
check("accuracy = 1/4", close(r["accuracy"], 0.25))
check("invalid output counted (None -> '<invalid>')", r["invalid_outputs"] == 1)
# included: TP=1 FP=1 FN=1 -> F1 .5 ; not included: 0 ; NEI: 0 ; N/A absent -> skipped; macro = .5/3
check("macro-F1 averages over classes present only", close(r["macro_f1"], 0.5 / 3))
check("absent class (not applicable) not counted as 0", "not applicable" not in r["macro_f1_classes"])
check("confusion matrix has an <invalid> column", r["confusion_matrix"]["cols_pred"][-1] == INVALID)
perfect = classification_report(["included", "not included"], ["included", "not included"], INCLUSION_LABELS)
check("perfect predictions -> accuracy 1 and macro-F1 1", close(perfect["accuracy"], 1) and close(perfect["macro_f1"], 1))

# ---- evidence empty-set rules and set arithmetic
check("both empty -> P=R=F1=1", evidence_row_scores([], []) == (1.0, 1.0, 1.0))
check("gold empty, pred non-empty -> P=0 R=1 F1=0", evidence_row_scores([], [1]) == (0.0, 1.0, 0.0))
check("gold non-empty, pred empty -> P=1 R=0 F1=0", evidence_row_scores([1], []) == (1.0, 0.0, 0.0))
p, rc, f = evidence_row_scores([1, 2], [2, 3])
check("partial overlap -> 0.5/0.5/0.5", close(p, 0.5) and close(rc, 0.5) and close(f, 0.5))
rep = evidence_report([[1, 2], [], [4]], [[2, 3], [], []])
check("micro pooled counts: TP1 FP1 FN2 -> P .5 R 1/3", close(rep["all_rows"]["micro_precision"], 0.5) and close(rep["all_rows"]["micro_recall"], 1 / 3))
check("gold-only block excludes empty-gold rows", rep["rows_with_gold_evidence"]["n"] == 2)

# ---- output parser
lab, ev, ok = parse_output('{"label": "included", "evidence": [0, 2]}', "inclusion", 5)
check("parses valid JSON", (lab, ev, ok) == ("included", [0, 2], True))
lab, ev, ok = parse_output('```json\n{"label": "Not Excluded", "evidence": []}\n```', "exclusion", 5)
check("parses fenced JSON, case-insensitive label", (lab, ev, ok) == ("not excluded", [], True))
lab, ev, ok = parse_output('{"label": "excluded", "evidence": [1]}', "inclusion", 5)
check("label from the wrong criterion type is INVALID (not silently mapped)", (lab, ok) == (None, False))
lab, ev, ok = parse_output("I think the patient qualifies.", "inclusion", 5)
check("free text without JSON is INVALID", (lab, ok) == (None, False))
lab, ev, ok = parse_output('{"label": "included", "evidence": [0, 99, -1]}', "inclusion", 5)
check("out-of-range sentence IDs are dropped", ev == [0] and ok)
check("numbered note split keeps IDs", split_sentences("0. A b.\n1. C d.\n2. E f.") == ["A b.", "C d.", "E f."])
check("unnumbered note is split on sentence ends", len(split_sentences("One sentence. Another one! A third?")) == 3)

# ---- split integrity (uses the committed manifest)
m = json.load(open(ROOT / "data" / "split_manifest.json"))
s = {k: set(v) for k, v in m["patients"].items()}
check("split sizes are 37/8/8 patients", (len(s["train"]), len(s["val"]), len(s["test"])) == (37, 8, 8))
check("no patient appears in two splits", not (s["train"] & s["val"] or s["train"] & s["test"] or s["val"] & s["test"]))
check("annotation counts 603/206/206", [m["counts"][k]["annotations"] for k in ("train", "val", "test")] == [603, 206, 206])
jl = ROOT / "data" / "train.jsonl"
if jl.exists():                                   # regenerated by data/prepare_data.py
    keys = set(json.loads(next(open(jl, encoding="utf-8"))).keys())
    check("model-input files contain no GPT-4 fields", not any(k.startswith("gpt4") or k == "explanation_correctness" for k in keys))
print(f"ALL {n_ok} UNIT TESTS PASSED")
